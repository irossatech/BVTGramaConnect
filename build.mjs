// Build the public website and the Super Admin console into dist/. No dependencies; Node 18+.
//
//   dist/           public website, served at /
//   dist/console/   Super Admin console, served at /console/
//
// Each output gets shared/ (Design Canvas runtime, React, design system, common
// images, config.js) and then the app's own files, at the same relative paths
// the pages already use. Files are copied byte for byte: the runtime re-reads
// index.html on boot, so nothing is minified or rewritten.
//
// Settings come from the environment, or from .env if it exists (see .env.example):
//   GC_API_BASE     API base URL both apps call (default "/api/v1")
//   GC_CONSOLE_URL  where the website's "Admin Login" leads (default "/console/")

import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));

function readDotEnv(path) {
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^["']|["']$/g, "");
  }
  return values;
}

const fileEnv = readDotEnv(join(root, ".env"));
const setting = (name, fallback) => process.env[name] || fileEnv[name] || fallback;
const config = {
  apiBase: setting("GC_API_BASE", "/api/v1"),
  consoleUrl: setting("GC_CONSOLE_URL", "/console/"),
};

const APPS = [
  { name: "website", src: "src", out: "dist" },
  { name: "console", src: "console/src", out: "dist/console" },
];

rmSync(join(root, "dist"), { recursive: true, force: true });
for (const app of APPS) {
  const out = join(root, app.out);
  cpSync(join(root, "shared"), out, { recursive: true });
  cpSync(join(root, app.src), out, { recursive: true });
  writeFileSync(
    join(out, "config.js"),
    `// Generated by build.mjs. Do not edit.\nwindow.GC_CONFIG = ${JSON.stringify(config)};\n`,
    "utf8"
  );
  console.log(`Built ${app.name.padEnd(8)} -> ${app.out}/`);
}
console.log(`  apiBase    ${config.apiBase}`);
console.log(`  consoleUrl ${config.consoleUrl}`);
